"""Capability-gated training: accept a block of updates only when held-out transfer rises and
retention holds (see ``docs/research_rl/CAPABILITY.md``).

This package re-exports the public names (each module's ``__all__``) of
``types``, ``tasks``, ``stats``, ``gate``, ``alarm``, ``weights``, ``scores``, ``spaces``, ``es``,
``probe``, ``tracker``, ``loop``, ``operators``, ``search``, ``edits``, ``pilot``, ``calibration`` and
``calibration_alarm``, so
``from research_rl.capability import GatedLoop, ESOperator`` works. The names of ``trl_gate``
(the TRL / ``transformers.TrainerCallback`` integration) are resolved lazily on first attribute
access, so ``import research_rl.capability`` does not import ``trl_gate``, ``research_rl.trainers``
or TRL. ``from research_rl.capability import *`` resolves every name of ``__all__`` and therefore
does import ``trl_gate``.

CPU-verified with tiny models only; every GPU / 7-8B statement is NOT_TESTED.
"""

